CREATE TYPE order_status AS ENUM ('paid', 'shipped', 'refunded');
CREATE TABLE authors (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, born date, country text);
CREATE TABLE books (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  author_id bigint REFERENCES authors(id),
  price numeric(8,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  in_stock boolean NOT NULL DEFAULT true,
  format book_format NOT NULL DEFAULT 'paperback',
  published date,
  tags text[] NOT NULL DEFAULT '{}',
  meta jsonb
);
CREATE TABLE customers (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), email text NOT NULL UNIQUE, name text NOT NULL, city text, joined_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE orders (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id uuid NOT NULL REFERENCES customers(id), status order_status NOT NULL DEFAULT 'paid', placed_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE order_items (order_id bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE, book_id bigint NOT NULL REFERENCES books(id), qty int NOT NULL DEFAULT 1, PRIMARY KEY (order_id, book_id));
CREATE TABLE reviews (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, book_id bigint NOT NULL REFERENCES books(id) ON DELETE CASCADE, stars int NOT NULL CHECK (stars BETWEEN 1 AND 5), body text, created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE events (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, kind text NOT NULL, at timestamptz NOT NULL, payload jsonb);
CREATE TABLE import_log (at timestamptz NOT NULL DEFAULT now(), line text);
CREATE INDEX ON books (author_id);
CREATE INDEX ON orders (customer_id);
CREATE INDEX ON reviews (book_id);
"

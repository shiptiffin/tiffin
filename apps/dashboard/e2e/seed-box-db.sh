#!/usr/bin/env bash
# Seeds a dev box (tiffin up, with services) for the Database console specs
# (db-*.spec.ts): a bookshop with links between tables, an enum, JSON, a list
# column, a composite key, a table without a key, a view, 50,000 events for
# the grid's speed, and a "warehouse" project with 34 linked tables for the
# schema diagram.
#
#   TIFFIN_CONFIG_DIR=/tmp/tiffin-dev-db e2e/seed-box-db.sh <tiffin binary>
#
# Throwaway boxes only: it applies configs and writes data.
set -euo pipefail
BIN="${1:?usage: seed-box-db.sh <tiffin binary>}"
: "${TIFFIN_CONFIG_DIR:?point TIFFIN_CONFIG_DIR at a dev box}"
CFG="$TIFFIN_CONFIG_DIR/boxes.json"
URL="$(jq -r '.boxes[.current].url' "$CFG")"
OWNER="$(jq -r '.boxes[.current].token' "$CFG")"
CA="$(jq -r '.boxes[.current].caFile' "$CFG")"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

api() { # api METHOD PATH [JSON]
  local m="$1" p="$2"
  shift 2
  curl -fsS --cacert "$CA" -X "$m" -H "Authorization: Bearer $OWNER" -H 'Content-Type: application/json' ${1:+-d "$1"} "$URL$p"
}
sql() { # sql <project> <statements>
  api POST "/v1/projects/$1/sql/write" "$(jq -nc --arg s "$2" '{sql:$s, timeoutSeconds:120}')" >/dev/null
}
apply() { # apply <dir> <intent>
  local hash
  hash="$("$BIN" plan "$1" --json | jq -r .hash)"
  "$BIN" apply "$1" --confirm "$hash" -m "$2" --json >/dev/null
}
wait_ready() {
  for _ in $(seq 1 90); do
    if api GET "/v1/projects/$1" | jq -e '[.status[]?.state] | all(. == "ready")' >/dev/null; then return 0; fi
    sleep 2
  done
  echo "project $1 is not ready" >&2
  return 1
}

for p in bookshop warehouse; do
  mkdir -p "$WORK/$p"
  printf 'import { defineConfig } from "tiffin-sdk";\nexport default defineConfig({ project: "%s", services: { postgres: {} } });\n' "$p" >"$WORK/$p/tiffin.config.ts"
  apply "$WORK/$p" "Start $p with a database"
done
wait_ready bookshop
wait_ready warehouse

sql bookshop "

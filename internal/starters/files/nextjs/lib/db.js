// On the box Next.js runs on Bun, which has a Postgres client built in
// (Bun.sql). An app switched to Node.js (runtime: "node") gets the same
// queries through postgres.js, whose API Bun.sql follows. Both read
// DATABASE_URL, which Tiffin sets. Locally, run `bun run dev` with it set.
import postgres from "postgres";

let pg;

export function db() {
  if (globalThis.Bun?.sql) return globalThis.Bun.sql;
  pg ??= postgres(process.env.DATABASE_URL);
  return pg;
}

let ready;

// Creates the table once per process. Idempotent, so every deploy can run
// it, and serialized with an advisory lock so instances do not race.
export function migrate() {
  ready ??= db()
    .begin(async (tx) => {
      await tx`select pg_advisory_xact_lock(hashtext('next-notes-migrate'))`;
      await tx`create table if not exists notes (
        id integer generated by default as identity primary key,
        text text not null check (length(text) between 1 and 280),
        created_at timestamptz not null default now()
      )`;
    })
    .catch((err) => {
      ready = undefined;
      throw err;
    });
  return ready;
}
